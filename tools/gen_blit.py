#!/usr/bin/env python3
"""Generate src/blit_kernel.h: one fully unrolled 72-output-pixel block of the 320->720 UYVYYY blit.

720/320 = 9/4, so 72 output pixels (12 UYVYYY groups... = 18 groups of 4 px = 108 bytes = 27 words)
map onto exactly 32 source pixels, the same pattern for all 10 blocks of a row. Output pixel o
samples source o*4//9. Each 4-pixel group takes its chroma from one sample (its 2nd pixel).
All loads happen before the stores, so the compiler need not assume aliasing.
"""
OUT = 72
src = [o * 4 // 9 for o in range(OUT)]
groups = OUT // 4
lines = ["/* generated by tools/gen_blit.py - do not edit */",
         "/* in: s (source row, block-relative), gy/gu8/gv8 tables; out: d (27 words) */"]
for i in range(32):
    lines.append(f"unsigned int q{i} = s[{i}];")
for i in range(32):
    lines.append(f"unsigned int y{i} = gy[q{i}];")
for k in range(groups):
    c = src[4 * k + 1]
    lines.append(f"unsigned int u{k} = gu8[q{c}], v{k} = gv8[q{c}];")
bytes_ = []
for k in range(groups):
    p = [src[4 * k + j] for j in range(4)]
    bytes_ += [f"u{k}", f"y{p[0]}", f"v{k}", f"y{p[1]}", f"y{p[2]}", f"y{p[3]}"]
assert len(bytes_) == 108
for w in range(27):
    b = bytes_[4 * w:4 * w + 4]
    lines.append(f"d[{w}] = {b[0]} | ({b[1]} << 8) | ({b[2]} << 16) | ({b[3]} << 24);")
open("src/blit_kernel.h", "w").write("\n".join(lines) + "\n")
print("wrote src/blit_kernel.h")
